#!/usr/bin/env node
// Regenerates docs/CATALOG.md and each plugin README.md from the frontmatter of every agent and skill.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const market = JSON.parse(fs.readFileSync(path.join(root, ".claude-plugin/marketplace.json"), "utf8"));

const fm = (file) => {
  const m = fs.readFileSync(file, "utf8").match(/^---\n([\s\S]*?)\n---/);
  const out = {};
  for (const line of (m?.[1] ?? "").split("\n")) {
    const kv = line.match(/^([A-Za-z-]+):\s*(.*)$/);
    if (kv) out[kv[1]] = kv[2].trim();
  }
  return out;
};
const cell = (s = "") => s.replace(/\|/g, "\\|");

let md = "# Catalog\n\nGenerated by `node scripts/catalog.mjs`. Do not edit by hand.\n";
for (const p of market.plugins) {
  const dir = path.join(root, p.source);
  const start = md.length;
  md += `\n## ${p.name}\n\n${p.description}\n`;

  const agentsDir = path.join(dir, "agents");
  if (fs.existsSync(agentsDir)) {
    md += `\n### Agents\n\n| Agent | Model | When to use |\n|---|---|---|\n`;
    for (const f of fs.readdirSync(agentsDir).filter((f) => f.endsWith(".md")).sort()) {
      const a = fm(path.join(agentsDir, f));
      md += `| \`${p.name}:${a.name}\` | ${a.model ?? "inherit"} | ${cell(a.description)} |\n`;
    }
  }

  const skillsDir = path.join(dir, "skills");
  if (fs.existsSync(skillsDir)) {
    const skills = fs.readdirSync(skillsDir).sort().map((s) => fm(path.join(skillsDir, s, "SKILL.md")));
    const workflows = skills.filter((s) => s["disable-model-invocation"] === "true");
    const knowledge = skills.filter((s) => s["disable-model-invocation"] !== "true");
    if (workflows.length) {
      md += `\n### Workflows (you run them)\n\n| Command | Arguments | What it does |\n|---|---|---|\n`;
      for (const s of workflows) md += `| \`/${p.name}:${s.name}\` | ${s["argument-hint"] ? "`" + cell(s["argument-hint"]) + "`" : ""} | ${cell(s.description.replace(/^Workflow\.\s*/, ""))} |\n`;
    }
    if (knowledge.length) {
      md += `\n### Skills (Claude loads them when relevant)\n\n| Skill | When it applies |\n|---|---|\n`;
      for (const s of knowledge) md += `| \`${s.name}\` | ${cell(s.description)} |\n`;
    }
  }

  const section = md.slice(start).replace(/^\n## .*\n/, "").replace(/^### /gm, "## ");
  const readme =
    `# ${p.name}\n\nPart of the [${market.name}](../../README.md) Claude Code marketplace. ` +
    `Generated by \`node scripts/catalog.mjs\`; do not edit by hand.\n\n` +
    `Install:\n\n\`\`\`bash\nclaude plugin marketplace add mauvies/${market.name}\n` +
    `claude plugin install ${p.name}@${market.name}\n\`\`\`\n` +
    section;
  fs.writeFileSync(path.join(dir, "README.md"), readme);
}
fs.writeFileSync(path.join(root, "docs/CATALOG.md"), md);
console.log("docs/CATALOG.md and plugin READMEs updated");
